export function searchEmoji(query = '', limit = 20) {
    if (typeof query !== 'string' || !Number.isInteger(limit) || limit < 1)
        return [];
    const normalized = query.trim().toLowerCase();
    return EMOJI
        .filter(([emoji, name, keywords]) => !normalized ||
            `${emoji} ${name} ${keywords}`.toLowerCase().includes(normalized))
        .slice(0, Math.min(limit, 50))
        .map(([emoji, name, keywords]) => ({emoji, name, keywords}));
}
